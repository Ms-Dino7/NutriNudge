        /* APP STATE MANAGEMENT */
        let currentSectionKey = 'fruits-info';
        let currentSlideIndex = 0;

        /* NAVIGATION CONTROLLER */
        function navigateTo(pageId) {
            // Hide all main view sections
            document.getElementById('view-home').classList.add('hidden');
            document.getElementById('view-about').classList.add('hidden');
            document.getElementById('view-contact').classList.add('hidden');
            document.getElementById('view-food-slider').classList.add('hidden');

            // Reset Top Navigation Pills state
            document.getElementById('nav-home').classList.remove('active');
            document.getElementById('nav-about').classList.remove('active');
            document.getElementById('nav-contact').classList.remove('active');

            // Show selected view
            if (pageId === 'home') {
                document.getElementById('view-home').classList.remove('hidden');
                document.getElementById('nav-home').classList.add('active');
            } else if (pageId === 'about') {
                document.getElementById('view-about').classList.remove('hidden');
                document.getElementById('nav-about').classList.add('active');
            } else if (pageId === 'contact') {
                document.getElementById('view-contact').classList.remove('hidden');
                document.getElementById('nav-contact').classList.add('active');
            } else if (pageId === 'food-slider') {
                document.getElementById('view-food-slider').classList.remove('hidden');
            }
            window.scrollTo({ top: 0, behavior: 'smooth' });
        }

        /* main home buttons */
        function startFoodSection(sectionKey) {
            currentSectionKey = sectionKey;
            currentSlideIndex = 0;
            renderSliderContent();
            navigateTo('food-slider');
        }

        /* Next / Back */
        function nextSlide() {
            const maxSlides = FOOD_DATA[currentSectionKey].slides.length;
            if (currentSlideIndex < maxSlides - 1) {
                currentSlideIndex++;
                renderSliderContent();
            }
        }

        function prevSlide() {
            if (currentSlideIndex > 0) {
                currentSlideIndex--;
                renderSliderContent();
            }
        }

        function renderSliderContent() {
            const sectionData = FOOD_DATA[currentSectionKey];
            const slideItems = sectionData.slides[currentSlideIndex];
            const isRecipe = currentSectionKey.includes('recipe');
            const totalSlides = sectionData.slides.length;

            // Title 
            document.getElementById('slider-category-title').innerText = `${sectionData.title} (${currentSlideIndex + 1}/${totalSlides})`;

            // Back / Next Buttons
            const btnBack = document.getElementById('btn-back');
            const btnNext = document.getElementById('btn-next');

            btnBack.disabled = (currentSlideIndex === 0);
            btnNext.disabled = (currentSlideIndex === totalSlides - 1);

            const container = document.getElementById('slide-cards-content');

            let htmlContent = '<div class="flex flex-col gap-8 md:gap-10 items-center w-full">';

            slideItems.forEach(item => {
                htmlContent += `
                    <div class="flex flex-col sm:flex-row items-center sm:items-start gap-4 md:gap-8 w-full max-w-3xl">
                        <!-- Food Square/Squircle Thumbnail Image -->
                        <img src="${item.img}" 
                             alt="${item.name}" 
                             class="food-thumb"
                             onerror="this.src='https://placehold.co/140x140/558028/ffffff?text=${encodeURIComponent(item.name)}'">
                        
                        <!-- Food Content Description / Ingredients -->
                        <div class="flex-1 text-center sm:text-left pt-1">
                            ${!isRecipe ? `
                                <!-- Benefit Info View Text -->
                                <p class="text-base md:text-xl font-medium leading-relaxed text-title-dark text-outline-style">
                                    ${item.text}
                                </p>
                            ` : `
                                <!-- Recipe Ingredients View Text -->
                                <h4 class="font-rounded font-bold text-xl md:text-2xl text-title-dark text-outline-style mb-2">
                                    ${item.name}:
                                </h4>
                                <ul class="space-y-1">
                                    ${item.ingredients.map(ing => `
                                        <li class="text-base md:text-xl font-medium text-title-dark text-outline-style">
                                            ${ing}
                                        </li>
                                    `).join('')}
                                </ul>
                            `}
                        </div>
                    </div>
                `;
            });

            htmlContent += '</div>';
            container.innerHTML = htmlContent;
        }

        window.addEventListener('DOMContentLoaded', () => {
            navigateTo('home');
        });
